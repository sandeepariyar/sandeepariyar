const assert = require('node:assert/strict');
const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const modelFile = path.join(__dirname,'../preview/model.js');
vm.runInThisContext(fs.readFileSync(modelFile,'utf8'),{filename:modelFile});
const m = global.ThreadModel;
assert.equal(m.products.length,1284,'catalog size');
assert.equal(m.productsAtRisk(),43,'flagged catalog count');
assert.equal(m.products[0].name,'Style Knit Crew','initial product');
const base = m.simulate(m.first,m.initialSettings);
assert.equal(base.weeks.length,8,'8-week model');
assert.ok(base.impactUnits>0,'initial scenario has projected exposure');
const mitigation = m.simulate(m.first,{...m.initialSettings,capacity:30,transfer:1000,transport:'express'});
assert.ok(mitigation.impactUnits<=base.impactUnits,'mitigation reduces shortfalls');
const repeat=m.simulate(m.first,m.initialSettings);
assert.deepEqual(base,repeat,'deterministic repeated calculation');
const risk=m.portfolioRisk(m.initialSettings);
assert.equal(risk.items.length,43,'portfolio flag scope');
assert.ok(risk.atRisk<=43,'projected risk is a subset of flagged sample');
console.log('PASS — catalog consistency, deterministic engine, mitigations, and portfolio scope');
console.log('Default scenario:',base.impactUnits,'unmet units,',base.proposedStockouts,'shortfall weeks,',base.service.toFixed(1)+'% service');
console.log('Mitigated scenario:',mitigation.impactUnits,'unmet units');
